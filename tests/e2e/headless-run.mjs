#!/usr/bin/env node
/**
 * DSH headless driver for `ai-compiler` acceptance tests.
 *
 * The shipped `@deepseek-ai/dsh-headless` bundle composes NO preset roster
 * (packages/bundle/headless/cordis.patch.yml) and `assertAdoptable()` refuses a
 * session that recorded one. P6 verification therefore boots a Scratch profile
 * that is byte-for-byte `@deepseek-ai/dsh-base` + `@deepseek-ai/dsh-headless`
 * **plus a `--patch` overlay** that inserts the preset registry, the four
 * shipped preset declarations and the `preset-ai-compiler` row from the same
 * bundle source the Web profile installs.
 *
 * The overlay is composed here (never hand-written) from:
 *   - the shipped web-app preset files (stand-ins for standard/ptc/minimal/cordis
 *     so that `preset-minimal`'s `compaction` rows exist where expected),
 *   - `config/bundle-ai-compiler/cordis.patch.yml` (the real deliverable).
 *
 * Every run writes under `evidence/headless/<run-id>/`:
 *   raw.stdout, raw.stderr, result.json (exit code + parsed run events).
 *
 * Usage: node headless-run.mjs --out <dir> [--patch <extra.yml>]... -- <task text>
 * Exit: the dsh process' exit code (0 success, 1 failure, 2 harness error).
 */
import { spawnSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { layout } from '../../scripts/lib/paths.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../..')
const argv = process.argv.slice(2)
const outIndex = argv.indexOf('--out')
if (outIndex < 0) {
  console.error('usage: headless-run.mjs --out <dir> [--patch <yml>]... -- <task>')
  process.exit(2)
}
const outDir = resolve(argv[outIndex + 1])
const extras = []
for (let i = 0; i < argv.length; i += 1) {
  if (argv[i] === '--patch') extras.push(resolve(argv[i + 1]))
}
const separator = argv.indexOf('--')
const task = separator < 0 ? '' : argv.slice(separator + 1).join(' ')
if (task.trim() === '') {
  console.error('a task is required after `--`')
  process.exit(2)
}

/** The preset-plane overlay for a preset-less profile. */
function presetOverlay() {
  const webPresets = join(layout.dshCheckout, 'packages/bundle/web-app/presets')
  const lines = [
    '# GENERATED by tests/e2e/headless-run.mjs — do not edit.',
    '# Adds the preset plane to a headless profile: registry + shipped preset',
    '# rows (as inert stand-ins where their child plugins are absent) + ai-compiler.',
    '- insert:',
    "    - id: agent-preset-registry",
    "      name: '@deepseek-ai/dsh-agent-preset-registry'",
    '      config:',
    '        default: standard',
  ]
  // Inline selected presets verbatim: their `insert:` list is a YAML array, so
  // re-emit the file's first inserted row under our own insert block.
  const inline = (file) => {
    const text = readFileSync(join(webPresets, file), 'utf8')
    const start = text.indexOf('    - id:')
    return text.slice(start).replace(/\n?$/u, '\n')
  }
  for (const file of ['standard.patch.yml', 'ptc.patch.yml', 'minimal.patch.yml', 'cordis.patch.yml']) {
    lines.push(inline(file).replace(/\n$/u, ''))
  }
  const real = readFileSync(join(repo, 'config/bundle-ai-compiler/cordis.patch.yml'), 'utf8')
  const realStart = real.indexOf('    - id: preset-ai-compiler')
  lines.push(real.slice(realStart).replace(/\n?$/u, ''))
  return `${lines.join('\n')}\n`
}

/**
 * Model-plane overlay. Keys live ONLY in `$DSH_HOME/.credentials.yaml` (the
 * credential store the Web Models page writes) and the launch environment
 * carries none, so the `credentials` row is mounted and the default route is
 * pinned to the profile provider `magpie`. This is the profile's EXISTING
 * model choice copied verbatim; no key is read, printed, or written here.
 */
function modelOverlay() {
  return [
    '# GENERATED by tests/e2e/headless-run.mjs — do not edit.',
    '- id: llm-pi-ai',
    "  name: '@deepseek-ai/dsh-llm-pi-ai'",
    '  config:',
    '    providers:',
    '      magpie:',
    '        apiKeyEnv: MAGPIE_API_KEY',
    '        api: openai-completions',
    '        baseURL: https://api.1031989.xyz',
    '        models:',
    '          - id: auto/deepseek-v4.1-flash',
    '            name: DeepSeek V4.1 Flash',
    '            contextWindow: 1048576',
    '            maxTokens: 393216',
    '- id: credentials',
    "  name: '@deepseek-ai/dsh-credentials-local'",
    '  disabled: false',
    '- id: agent-default-model',
    "  name: '@deepseek-ai/dsh-agent-default-model'",
    '  config:',
    '    provider: magpie',
    '    model: auto/deepseek-v4.1-flash',
    '',
  ].join('\n')
}

mkdirSync(outDir, { recursive: true })
const overlayPath = join(outDir, 'preset-overlay.yml')
writeFileSync(overlayPath, presetOverlay())
const modelOverlayPath = join(outDir, 'model-overlay.yml')
writeFileSync(modelOverlayPath, modelOverlay())

/**
 * One profile per run: the shipped `web` bundle stack (which owns the host
 * plane and the preset roster) plus the pure runner bundle
 * `@deepseek-ai/dsh-headless` (one-shot task, `--json`, no Host/HTTP).
 *
 * WHY NOT `--profile headless`: that profile initializes from the template
 * `[dsh-base, dsh-headless]`, which has neither the preset registry nor the
 * web-app host-plane disables. Overlays that merely INSERT the preset rows
 * leave the base plane's own `tool-bash`/`tool-fs`/`tool-subagent-goal` rows
 * enabled, and `dsh-headless` creates its Agent directly, so the run silently
 * used the host tools (measured in evidence/e2e/case-a/run-01). Adding the
 * `dsh-headless` bundle to the web template gives the one-shot runner with the
 * SAME agent plane the Web GUI uses.
 *
 * WHY NOT create the resources-service plugins: `webserver`/`web-runtime`/
 * `connection`/`agent-loop` are *required* startup entries whenever enabled
 * (`requiredStartupEntryIds` in app-boot), so the supporting Web rows are
 * disabled here; they would otherwise wait forever for services a one-shot
 * process never starts.
 */
const dsh = join(layout.dshCheckout, 'apps/cli/lib/bin.js')
const scratchProfile = process.env.DSH_SCRATCH_PROFILE ?? 'ai-compiler-scratch'
const profilesRoot = join(layout.dshHome, 'profiles', scratchProfile)
// `agent-loop` is NOT disabled: it owns the Agent factory the runner needs.
const SUPPORTING_ROWS = ['webserver', 'web-runtime', 'connection', 'modules', 'account-controller',
  'session-log-download', 'open-in-app', 'directory-picker', 'session-controller', 'schedule',
  'harness-dev-context', 'client-hmr', 'file-upload', 'ui-deliverables', 'ui-agent-preset', 'settings-controller', 'web-startup']
if (process.env.DSH_KEEP_SCRATCH !== '1' || !existsSync(profilesRoot)) {
  rmSync(profilesRoot, { recursive: true, force: true })
  mkdirSync(profilesRoot, { recursive: true })
  writeFileSync(join(profilesRoot, 'cordis.yml'), '# dsh profile root — composed as patches.\n[]\n')
  writeFileSync(join(profilesRoot, 'pnpm-workspace.yaml'), 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n')
  writeFileSync(join(profilesRoot, 'package.json'), `${JSON.stringify({
    name: `dsh-profile-${scratchProfile}`,
    private: true,
    // Bare workspace packages a preset/host row names are resolved by the
    // installation (the checkout's package table). lsp-stdio and tool-lsp are
    // NOT installation dependencies in rc.3, so a profile that mounts them must
    // depend on the checkout itself; pnpm hoists that tree into this profile's
    // node_modules, which is what lets those two rows import.
    dependencies: {
      '@local/dsh-ai-compiler-preset': `link:${join(repo, 'config/bundle-ai-compiler')}`,
      // lsp-stdio/tool-lsp are not dependencies of this dsh installation, so the
      // profile must carry them itself; the live profile installs the same three
      // links with `dsh plugin --profile web add --link …`.
      '@deepseek-ai/dsh-lsp': `link:${join(layout.dshCheckout, 'packages/lsp/lsp')}`,
      '@deepseek-ai/dsh-lsp-stdio': `link:${join(layout.dshCheckout, 'packages/lsp/lsp-stdio')}`,
      '@deepseek-ai/dsh-tool-lsp': `link:${join(layout.dshCheckout, 'packages/lsp/tool-lsp')}`,
    },
    dsh: { profile: { bundles: ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app', '@deepseek-ai/dsh-headless', '@local/dsh-ai-compiler-preset'] } },
  }, null, 2)}\n`)
  const installed = spawnSync('pnpm', ['install', '--ignore-scripts'], { cwd: profilesRoot, encoding: 'utf8' })
  if (installed.status !== 0) {
    console.error(`scratch profile install failed: ${installed.stderr ?? ''}`)
    process.exit(2)
  }
  // Model rows are copied verbatim from the live profile's patch file so a key
  // rotation or model change is picked up without editing this driver.
  const live = readFileSync(join(layout.profiles.web, 'cordis.patch.yml'), 'utf8')
  const keep = live.split('\n- id: ').filter(block => /^(llm-pi-ai|agent-default-model|permission)/u.test(block))
  const lines = [
    '# Scratch profile for ai-compiler acceptance runs (generated by tests/e2e/headless-run.mjs).',
    '# Model/permission rows are copied verbatim from the live web profile (not edits).',
    ...keep.map(block => `\n- id: ${block}`),
    '',
    '# One-shot run: the Web transport rows cannot start and are not needed.',
    ...SUPPORTING_ROWS.map(id => `- id: ${id}\n  disabled: true`),
    '',
    '# ai-compiler is the default preset for every session this profile creates.',
    '- id: agent-preset-registry',
    "  name: '@deepseek-ai/dsh-agent-preset-registry'",
    '  config:',
    '    default: ai-compiler',
    '',
  ]
  writeFileSync(join(profilesRoot, 'cordis.patch.yml'), `${lines.join('\n').replace(/\n\n- id:/gu, '\n- id:')}\n`)
}
const args = [dsh, '--profile', scratchProfile, '--patch', overlayPath, '--patch', modelOverlayPath]
for (const extra of extras) args.push('--patch', extra)
args.push('--json', task)
const started = Date.now()
const run = spawnSync(process.execPath, args, {
  cwd: process.cwd(),
  encoding: 'utf8',
  timeout: Number(process.env.DSH_HEADLESS_TIMEOUT_MS ?? 1_800_000),
  maxBuffer: 256 * 1024 * 1024,
  env: process.env,
})
const elapsedMs = Date.now() - started
writeFileSync(join(outDir, 'raw.stdout'), run.stdout ?? '')
writeFileSync(join(outDir, 'raw.stderr'), run.stderr ?? '')
const events = (run.stdout ?? '')
  .split('\n')
  .filter(line => line.trim() !== '')
  .flatMap((line) => {
    try { return [JSON.parse(line)] } catch { return [] }
  })
const result = {
  argv: args,
  task,
  exitCode: run.status,
  signal: run.signal,
  elapsedMs,
  eventCount: events.length,
  events,
}
writeFileSync(join(outDir, 'result.json'), `${JSON.stringify(result, null, 2)}\n`)
console.log(JSON.stringify({
  outDir, exitCode: run.status, elapsedMs, eventCount: events.length,
  stderrTail: (run.stderr ?? '').trim().split('\n').slice(-5).join('\n'),
}, null, 2))
process.exit(run.status ?? 1)
